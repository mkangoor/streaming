"""Load the data contract and derive DDL, expectations, UC governance SQL and docs from it."""

from __future__ import annotations

from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path
from typing import Any

import yaml

from tax_rag.names import Names

VALID_ACTIONS = ("drop", "warn", "fail")
VALID_MANAGERS = ("pipeline", "job")


def sql_string(value: str) -> str:
    """Single-quoted Spark SQL string literal."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _tag_list(tags: dict[str, str]) -> str:
    return ", ".join(f"{sql_string(k)} = {sql_string(str(v))}" for k, v in sorted(tags.items()))


@dataclass(frozen=True)
class Column:
    name: str
    type: str
    description: str
    tags: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class Table:
    name: str
    layer: str
    managed_by: str
    description: str
    columns: tuple[Column, ...]
    explicit_schema: bool = True
    tags: dict[str, str] = field(default_factory=dict)
    table_properties: dict[str, str] = field(default_factory=dict)
    cluster_by: tuple[str, ...] = ()

    @property
    def column_names(self) -> list[str]:
        return [c.name for c in self.columns]

    @property
    def sql_kind(self) -> str:
        return "STREAMING TABLE" if self.managed_by == "pipeline" else "TABLE"


@dataclass(frozen=True)
class QualityRule:
    name: str
    constraint: str
    action: str
    description: str


@dataclass(frozen=True)
class Contract:
    name: str
    version: int
    owner: str
    description: str
    default_tags: dict[str, str]
    tables: dict[str, Table]
    quality_rules: tuple[QualityRule, ...]
    cdc: dict[str, Any]

    def table(self, name: str) -> Table:
        try:
            return self.tables[name]
        except KeyError:
            raise KeyError(f"Table {name!r} is not in contract {self.name!r}") from None

    def ddl(self, name: str) -> str:
        """Column list with comments, usable as a Lakeflow `schema=` or CREATE TABLE body."""
        return ", ".join(
            f"`{c.name}` {c.type} COMMENT {sql_string(c.description)}"
            for c in self.table(name).columns
        )

    def rules(self, action: str) -> dict[str, str]:
        return {r.name: r.constraint for r in self.quality_rules if r.action == action}

    def table_tags(self, name: str) -> dict[str, str]:
        table = self.table(name)
        return {**self.default_tags, "layer": table.layer, **table.tags}

    def create_table_sql(self, names: Names, name: str) -> str:
        table = self.table(name)
        if table.managed_by != "job":
            raise ValueError(f"{name} is pipeline-managed; Lakeflow creates it")
        parts = [f"CREATE TABLE IF NOT EXISTS {names.sql(name)} ({self.ddl(name)})", "USING DELTA"]
        if table.cluster_by:
            parts.append("CLUSTER BY (" + ", ".join(f"`{c}`" for c in table.cluster_by) + ")")
        parts.append(f"COMMENT {sql_string(table.description)}")
        if table.table_properties:
            props = ", ".join(
                f"{sql_string(k)} = {sql_string(v)}"
                for k, v in sorted(table.table_properties.items())
            )
            parts.append(f"TBLPROPERTIES ({props})")
        return "\n".join(parts)

    def governance_sql(self, names: Names) -> list[str]:
        """Idempotent statements applying comments + tags in Unity Catalog.

        Lakeflow already sets table/column comments for pipeline tables with an explicit
        schema, so comments are only (re)applied to job-managed tables here.
        """
        statements: list[str] = []
        for table in self.tables.values():
            fqn = names.sql(table.name)
            kind = table.sql_kind
            if table.managed_by == "job":
                statements.append(f"COMMENT ON TABLE {fqn} IS {sql_string(table.description)}")
                for col in table.columns:
                    statements.append(
                        f"ALTER TABLE {fqn} ALTER COLUMN `{col.name}` COMMENT {sql_string(col.description)}"
                    )
            statements.append(
                f"ALTER {kind} {fqn} SET TAGS ({_tag_list(self.table_tags(table.name))})"
            )
            for col in table.columns:
                if col.tags:
                    statements.append(
                        f"ALTER {kind} {fqn} ALTER COLUMN `{col.name}` SET TAGS ({_tag_list(col.tags)})"
                    )
        return statements

    def to_markdown(self) -> str:
        lines = [
            f"# Data dictionary: `{self.name}` (contract v{self.version})",
            "",
            "<!-- GENERATED by scripts/gen_docs.py from "
            "src/tax_rag/contracts/tax_documents.yml. Do not edit by hand. -->",
            "",
            self.description.strip(),
            "",
            f"**Owner:** {self.owner}  ",
            "**Default tags:** "
            + ", ".join(f"`{k}={v}`" for k, v in sorted(self.default_tags.items())),
            "",
            "| Table | Layer | Managed by | Description |",
            "|---|---|---|---|",
        ]
        for t in self.tables.values():
            lines.append(f"| `{t.name}` | {t.layer} | {t.managed_by} | {t.description.strip()} |")
        for t in self.tables.values():
            lines += ["", f"## `{t.name}`", "", t.description.strip(), ""]
            if t.table_properties:
                props = ", ".join(f"`{k}={v}`" for k, v in sorted(t.table_properties.items()))
                lines += [f"**Table properties:** {props}", ""]
            lines += ["| Column | Type | Description | Tags |", "|---|---|---|---|"]
            for c in t.columns:
                tags = ", ".join(f"`{k}={v}`" for k, v in sorted(c.tags.items()))
                ctype = c.type.replace("|", "\\|")
                lines.append(f"| `{c.name}` | `{ctype}` | {c.description} | {tags} |")
        lines += [
            "",
            "## Quality rules (`silver_tax_document_events`)",
            "",
            "| Rule | Action | Constraint | Why |",
            "|---|---|---|---|",
        ]
        for r in self.quality_rules:
            lines.append(f"| `{r.name}` | {r.action} | `{r.constraint}` | {r.description} |")
        cdc = self.cdc
        lines += [
            "",
            "## Change data capture",
            "",
            f"- Keys: {', '.join(f'`{k}`' for k in cdc['keys'])}",
            f"- Sequenced by: {', '.join(f'`{k}`' for k in cdc['sequence_by'])}",
            f"- Delete when: `{cdc['delete_condition']}`",
            f"- Excluded from current/history tables: "
            f"{', '.join(f'`{k}`' for k in cdc['except_columns'])}",
            "",
        ]
        return "\n".join(lines)


def _parse(raw: dict[str, Any]) -> Contract:
    tables: dict[str, Table] = {}
    for name, spec in raw["tables"].items():
        managed_by = spec["managed_by"]
        if managed_by not in VALID_MANAGERS:
            raise ValueError(f"{name}: managed_by must be one of {VALID_MANAGERS}")
        columns = tuple(
            Column(c["name"], c["type"], str(c["description"]).strip(), dict(c.get("tags") or {}))
            for c in spec["columns"]
        )
        if len({c.name for c in columns}) != len(columns):
            raise ValueError(f"{name}: duplicate column names")
        tables[name] = Table(
            name=name,
            layer=spec["layer"],
            managed_by=managed_by,
            description=str(spec["description"]).strip(),
            columns=columns,
            explicit_schema=bool(spec.get("explicit_schema", True)),
            tags=dict(spec.get("tags") or {}),
            table_properties={k: str(v) for k, v in (spec.get("table_properties") or {}).items()},
            cluster_by=tuple(spec.get("cluster_by") or ()),
        )
    rules = []
    for r in raw.get("quality_rules", []):
        if r["action"] not in VALID_ACTIONS:
            raise ValueError(f"rule {r['name']}: action must be one of {VALID_ACTIONS}")
        rules.append(QualityRule(r["name"], r["constraint"], r["action"], r.get("description", "")))
    return Contract(
        name=raw["contract"],
        version=int(raw["version"]),
        owner=raw["owner"],
        description=str(raw["description"]).strip(),
        default_tags={k: str(v) for k, v in raw.get("defaults", {}).get("tags", {}).items()},
        tables=tables,
        quality_rules=tuple(rules),
        cdc=dict(raw["cdc"]),
    )


def load_contract(path: str | Path | None = None) -> Contract:
    if path is None:
        text = resources.files("tax_rag.contracts").joinpath("tax_documents.yml").read_text("utf-8")
    else:
        text = Path(path).read_text("utf-8")
    return _parse(yaml.safe_load(text))
